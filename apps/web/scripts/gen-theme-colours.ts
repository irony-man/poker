/**
 * Emit apps/web/app/theme.colours.generated.css from design-tokens/mapping.ts.
 *
 *   npm run gen:colours -w @poker/web
 *   node --experimental-strip-types scripts/gen-theme-colours.ts --check
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { blocks, dsGradients, dsRoles, paletteOnly, type ModeName } from '../design-tokens/mapping.ts';
import { dsTriplet, hexToTriplet, primitiveHex, resolveDeclaration, roleRaw } from '../design-tokens/resolve.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'app/theme.colours.generated.css');

function paletteSelector(selector: string): string {
  return selector
    .split(',')
    .map((part) => {
      const trimmed = part.trim();
      if (trimmed === ':root') return "html[data-palette='v2']";
      if (trimmed.startsWith('html[')) return trimmed.replace(/^html\[/, "html[data-palette='v2'][");
      return `html[data-palette='v2'] ${trimmed}`;
    })
    .join(',\n');
}

function formatDecls(decls: Record<string, string>): string {
  return Object.entries(decls)
    .map(([key, value]) => `  ${key}: ${value};`)
    .join('\n');
}

function emit(selector: string, decls: Record<string, string>): string {
  const keys = Object.keys(decls);
  if (keys.length === 0) return '';
  return `${selector} {\n${formatDecls(decls)}\n}\n`;
}

